"""Build WOFF2 subsets from the original fonts. Requires fonttools and brotli."""

from itertools import groupby
from pathlib import Path
from string import printable
from textwrap import fill

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/assets/fonts"
CSS = ROOT / "src/assets/styles/ticket-fonts.css"
SOURCES = (
    "src/components/TicketArtwork.vue",
    "src/components/LeftTicketCard.vue",
    "src/components/overview/demoFields.js",
    "src/components/overview/demoMonitor.js",
    "src/composables/useTicketShared.js",
    "src/utils/ticketShared.js",
)
FONTS = (
    ("SimSun", "simsun", "simsun.ttf", 0),
    ("FZCDXK", "fangzheng", "FZCDXK.TTF", -1),
)
BAND_SIZE = 0x1000


def unicode_range(points):
    ranges = []
    for _, run in groupby(enumerate(sorted(points)), lambda item: item[1] - item[0]):
        codes = [point for _, point in run]
        start, end = codes[0], codes[-1]
        ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return fill(", ".join(ranges), width=72, subsequent_indent="    ", break_on_hyphens=False)


def write_subset(source, face, filename, points, original_metrics):
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    with TTFont(source, fontNumber=face, recalcTimestamp=False) as font:
        builder = subset.Subsetter(options=options)
        builder.populate(unicodes=points)
        builder.subset(font)
        font.flavor = "woff2"
        font.save(OUTPUT / filename)

    with TTFont(OUTPUT / filename) as font:
        metrics = font["hmtx"].metrics
        actual = {point: metrics[glyph] for point, glyph in font.getBestCmap().items()}
        expected = {point: original_metrics[point] for point in points}
        if actual != expected:
            raise ValueError(f"{filename} changed Unicode coverage or horizontal metrics")


def font_face(family, filename, ranges):
    return (
        "@font-face {\n"
        f'  font-family: "{family}";\n'
        f'  src: url("../fonts/{filename}") format("woff2");\n'
        "  font-weight: 400;\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        f"  unicode-range: {ranges};\n"
        "}\n"
    )


def build_font(family, slug, filename, face, demo_points):
    source = ROOT / "public" / filename
    with TTFont(source, fontNumber=face) as font:
        metrics = font["hmtx"].metrics
        original_metrics = {point: metrics[glyph] for point, glyph in font.getBestCmap().items()}

    demo = original_metrics.keys() & demo_points
    remaining = original_metrics.keys() - demo
    rules = []
    for band, group in groupby(sorted(remaining), lambda point: point // BAND_SIZE):
        points = list(group)
        output = f"{slug}-{band:02x}.woff2"
        write_subset(source, face, output, points, original_metrics)
        rules.append(font_face(family, output, f"U+{points[0]:X}-{points[-1]:X}"))

    # The last face wins for demo characters that also fall within a band.
    output = f"{slug}-demo.woff2"
    write_subset(source, face, output, demo, original_metrics)
    rules.append(font_face(family, output, unicode_range(demo)))
    return rules


def main():
    demo_points = set(map(ord, printable + "\u00A0"))
    for source in SOURCES:
        demo_points.update(map(ord, (ROOT / source).read_text(encoding="utf-8")))

    OUTPUT.mkdir(exist_ok=True)
    rules = ["/* Generated by scripts/build-web-fonts.py. */\n"]
    for family, slug, filename, face in FONTS:
        rules.extend(build_font(family, slug, filename, face, demo_points))
    CSS.write_text("\n".join(rules), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
